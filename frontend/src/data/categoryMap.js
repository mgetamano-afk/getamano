/** Return every subcategory string that is NOT in the suggested set for `mainCategory`. */
export function getOtherSubcategories(mainCategory) {
  const suggested = CATEGORY_MAP[mainCategory] || [];
  const all = Object.values(CATEGORY_MAP).flat();
  const unique = Array.from(new Set(all));
  return unique.filter((sub) => !suggested.includes(sub));
}

/** Return suggested subs (always defined as a fresh array). */
export function getSuggestedSubcategories(mainCategory) {
  return CATEGORY_MAP[mainCategory] ? [...CATEGORY_MAP[mainCategory]] : [];
}
